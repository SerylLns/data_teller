module DataTeller
  # The columns a query may read, from the declarations (T37, ADR 0005 D6): what the database role gets a SELECT on, and nothing
  # else. A column left out refuses legitimate queries; one too many is readable by a bug of the validator or the compiler. The
  # list follows what the compiler touches: declared columns, join keys of paths, every column of the tenant filter, and the
  # columns compared by scopes and default_scopes.
  #
  # Calls the scopes of segments and reads the columns of the models, so never at boot (ADR 0004 D6).
  class ReaderGrants
    def initialize(registry:, tenant_model_name:)
      @registry = registry
      @tenant_model_name = tenant_model_name
    end

    # { "orders" => ["account_id", "status", ...] }, sorted, by table name as the models give it.
    def columns
      @columns ||= begin
        found = Hash.new { |hash, table| hash[table] = Set.new }
        @registry.datasets.each { |dataset| collect(dataset, found) }
        found.sort.to_h { |table, names| [ table, names.sort.freeze ] }.freeze
      end
    end

    # The SQL to give the role exactly these columns. Printed for the developer to review and run, never run by the gem: creating
    # roles and granting is the job of whoever owns the database.
    def sql(role:, member:)
      ActiveRecord::Base.with_connection do |connection|
        quoted = connection.quote_column_name(role)
        schemas = schemas_of(connection)

        [
          "-- Generated by `rake data_teller:grants` from the DataTeller declarations. Review it, then run it in one transaction",
          "-- (a migration is one; with psql, use --single-transaction) as a user allowed to create roles and to grant on these tables.",
          "-- Run it again after changing the declarations: `rake data_teller:check` fails until the grants match them.",
          "DO $$ BEGIN",
          "  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = #{connection.quote(role)}) THEN",
          "    CREATE ROLE #{quoted} NOLOGIN;",
          "  END IF;",
          "END $$;",
          "-- The app's database user switches to this role for each query (SET LOCAL ROLE), so it must be a member of it.",
          "GRANT #{quoted} TO #{connection.quote_column_name(member)};",
          "-- From nothing, so that a column no longer declared stops being readable.",
          *schemas.map { |schema| "REVOKE ALL ON ALL TABLES IN SCHEMA #{connection.quote_column_name(schema)} FROM #{quoted};" },
          *schemas.map { |schema| "GRANT USAGE ON SCHEMA #{connection.quote_column_name(schema)} TO #{quoted};" },
          *columns.map do |table, names|
            "GRANT SELECT (#{names.map { |name| connection.quote_column_name(name) }.join(', ')}) ON #{connection.quote_table_name(table)} TO #{quoted};"
          end
        ].join("\n") + "\n"
      end
    end

    private

    # Where the tables are, as the search_path resolves them: a REVOKE and a USAGE for each.
    def schemas_of(connection)
      columns.keys.filter_map do |table|
        connection.select_value(<<~SQL)
          SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
          WHERE c.oid = to_regclass(#{connection.quote(connection.quote_table_name(table))})
        SQL
      end.uniq.sort
    end

    def collect(dataset, found)
      klass = ModelLookup.active_record_class(dataset.model_name)
      return unless klass # ModelValidator reports it

      table = found[klass.table_name]
      dataset.dimensions.each_value { |dimension| table << dimension.column }
      dataset.metrics.each_value { |metric| collect_metric(klass, metric, found) }
      dataset.segments.each_value { |segment| collect_segment(klass, segment, table) }
      table.merge(compared_columns(klass, default_scope_conditions(klass)))
      collect_tenant_path(klass, dataset.tenant_path, found)
      collect_dimension_paths(klass, dataset, found)
    end

    def collect_metric(klass, metric, found)
      return unless metric.column

      owner, name = ModelLookup.column_owner(klass, metric.column)
      return unless owner # ModelValidator reports it

      found[owner.table_name] << name
      ModelLookup.follow_metric_path(klass, metric.steps) { |reflection| collect_join(reflection, found) }
    end

    # A hash key is a column, or an association that Active Record reads through its foreign key.
    def collect_segment(klass, segment, table)
      if segment.scope?
        table.merge(compared_columns(klass, scope_conditions(klass, segment.scope)))
      else
        segment.where.each_key do |key|
          reflection = klass.reflect_on_association(key)
          table << (reflection&.belongs_to? ? reflection.foreign_key.to_s : key.to_s)
        end
      end
    end

    # As TenantScope builds it: the foreign key of each step, and the key each parent is selected by. On the tenant model itself,
    # its primary key. The tenant's own table is never read: its id is a bound value.
    def collect_tenant_path(klass, path, found)
      return found[klass.table_name] << klass.primary_key.to_s if path.nil?

      path.each_with_index.reduce(klass) do |current, (step, index)|
        reflection = current.reflect_on_association(step)
        return unless reflection&.belongs_to? # the boot refuses it, and so does the compiler

        found[current.table_name] << reflection.foreign_key.to_s
        found[reflection.klass.table_name] << reflection.association_primary_key.to_s if index < path.size - 1
        reflection.klass
      end
    end

    # The joins of customer.city and the like. The datasets on the way are registered, so their own columns come with them.
    def collect_dimension_paths(klass, dataset, found)
      DimensionPaths.hops(dataset, registry: @registry, tenant_model_name: @tenant_model_name).each do |hop|
        ModelLookup.follow(klass, hop.steps) { |_current, _step, reflection| collect_join(reflection, found) }
      end
    end

    # Both sides of a join's ON, for a belongs_to (orders.customer_id = customers.id) as for a has_many.
    def collect_join(reflection, found)
      Array(reflection.join_foreign_key).each { |name| found[reflection.active_record.table_name] << name.to_s }
      Array(reflection.join_primary_key).each { |name| found[reflection.klass.table_name] << name.to_s }
    end

    # ScopeInspector refuses anything but comparisons of the model's own columns (ADR 0004 D4). A rejected scope adds nothing:
    # `rake data_teller:check` reports it, and the compiler refuses it.
    def scope_conditions(klass, name)
      ReadOnlyExecution.run(klass, timeout: SchemaValidator::SCOPE_CHECK_TIMEOUT) { ScopeInspector.conditions(klass, name) }
    rescue ScopeInspector::Rejected, ActiveRecord::StatementInvalid
      nil
    end

    # Includes the type condition of an STI subclass, which Active Record puts in the same place.
    def default_scope_conditions(klass)
      ScopeInspector.check_default_scope(klass)
      klass.all.where_clause.ast
    rescue ScopeInspector::Rejected
      nil
    end

    def compared_columns(klass, node)
      case node
      when Arel::Attributes::Attribute then node.relation.name == klass.table_name ? [ node.name.to_s ] : []
      when Arel::Nodes::HomogeneousIn then compared_columns(klass, node.attribute)
      when Arel::Nodes::Nary then node.children.flat_map { |child| compared_columns(klass, child) }
      when Arel::Nodes::Binary then compared_columns(klass, node.left) + compared_columns(klass, node.right)
      when Arel::Nodes::Unary then compared_columns(klass, node.expr)
      else []
      end
    end
  end
end
